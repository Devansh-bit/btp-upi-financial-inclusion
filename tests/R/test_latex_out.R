library(testthat)
library(data.table)
source("../../src/R/lib/latex_out.R")

test_that("fmt formats numbers", {
  expect_equal(fmt(38664.285, 1), "38{,}664.3")
  expect_equal(fmt(-10.56, 1), "$-$10.6")
  expect_equal(fmt(0.0000015, 7), "0.0000015")
  expect_equal(fmt(c(1, 1234567), 0), c("1", "1{,}234{,}567"))
})

test_that("latex_escape escapes special characters", {
  expect_equal(latex_escape("A & B_1"), "A \\& B\\_1")
  expect_equal(latex_escape("50% $5 #1 {x}"), "50\\% \\$5 \\#1 \\{x\\}")
})

test_that("test_bad_key", {
  expect_error(nv("Nat.count", 1, 1, "x"))
  expect_error(nv("nat count", 1, 1, "x"))
  e <- nv("st.count_pc.max.name.2018Q4", "A_B", source = "x")
  expect_equal(e$value, "A\\_B")
  expect_s3_class(nv("nat.count.2026Q2", 1, 0, "x"), "data.table")
})

test_that("test_non_finite", {
  expect_error(nv("a.b", NA_real_, 1, "x"))
  expect_error(nv("a.b", Inf, 1, "x"))
})

test_that("test_duplicate", {
  e <- rbind(nv("a.b", 1, 1, "x"), nv("a.b", 2, 1, "y"))
  expect_error(write_numbers(e, tempfile(), "gen.R"))
})

test_that("test_numbers_file", {
  p <- tempfile()
  write_numbers(rbind(nv("a.b", 1.5, 1, "src"), nv("c.d", "x", source = "s2")), p, "gen.R")
  l <- readLines(p)
  expect_equal(l[1], "% generated by gen.R; do not edit")
  expect_equal(l[2], "\\defval{a.b}{1.5}  % src")
  expect_equal(l[3], "\\defval{c.d}{x}  % s2")
})

test_that("test_tabular", {
  p <- tempfile()
  cells <- matrix(c("a", "1", "b", "2"), nrow = 2, byrow = TRUE)
  write_tabular(cells, p, "lr", "Name & Value \\\\")
  expect_equal(paste(readLines(p), collapse = "\n"),
    paste("\\begin{tabular}{lr}", "\\toprule", "Name & Value \\\\", "\\midrule",
          "a & 1 \\\\", "b & 2 \\\\", "\\bottomrule", "\\end{tabular}", sep = "\n"))
  expect_error(write_tabular(matrix(c("a", "1", "b"), nrow = 1), p, "lr", "H"))
})

test_that("longtable has caption and repeated header", {
  p <- tempfile()
  write_tabular(matrix(c("a", "1"), nrow = 1), p, "lr", "N & V \\\\",
                env = "longtable", caption = "Cap", label = "tab:x")
  expect_equal(paste(readLines(p), collapse = "\n"),
    paste("\\begin{longtable}{lr}", "\\caption{Cap}\\label{tab:x}\\\\", "\\toprule", "N & V \\\\",
          "\\midrule", "\\endfirsthead", "\\toprule", "N & V \\\\", "\\midrule", "\\endhead",
          "a & 1 \\\\", "\\bottomrule", "\\end{longtable}", sep = "\n"))
})
