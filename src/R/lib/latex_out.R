# Writers for LaTeX output: number definitions (\defval) and tables.
library(data.table)

# Fixed decimals, "{,}" thousands separator, "$-$" minus sign.
fmt <- function(x, digits) {
  stopifnot(is.numeric(x), length(digits) == 1L)
  s <- formatC(abs(x), format = "f", digits = digits, big.mark = "{,}")
  neg <- x < 0 & grepl("[1-9]", s)
  ifelse(neg, paste0("$-$", s), s)
}

# Escape the LaTeX special characters & % $ # _ { }.
latex_escape <- function(x) {
  gsub("([&%$#_{}])", "\\\\\\1", x)
}

KEY_REGEX <- "^[a-z][a-z0-9_]*(\\.[A-Za-z0-9_]+)*$"

# One entry for write_numbers. Numeric values use fmt(); character values use latex_escape().
nv <- function(key, value, digits = NULL, source) {
  stopifnot(length(key) == 1L, length(value) == 1L)
  if (!grepl(KEY_REGEX, key)) stop("invalid key: ", key)
  if (is.numeric(value)) {
    if (!is.finite(value)) stop("value is not finite for key: ", key)
    if (is.null(digits)) stop("digits missing for numeric key: ", key)
    txt <- fmt(value, digits)
  } else {
    txt <- latex_escape(as.character(value))
  }
  as.data.table(list(key = key, value = txt, source = source))
}

# Write one \defval line per entry, in the order given.
write_numbers <- function(entries, path, generator) {
  dup <- unique(entries$key[duplicated(entries$key)])
  if (length(dup) > 0L) stop("duplicate keys: ", paste(dup, collapse = ", "))
  lines <- c(paste0("% generated by ", generator, "; do not edit"),
             sprintf("\\defval{%s}{%s}  %% %s", entries$key, entries$value, entries$source))
  writeLines(lines, path)
}

# Write a table body from a character table of formatted cells.
write_tabular <- function(cells, path, align, header, env = "tabular",
                          caption = NULL, label = NULL) {
  cells <- as.matrix(cells)
  ncols <- nchar(gsub("[^A-Za-z]", "", gsub("\\{[^}]*\\}", "", align)))
  if (ncol(cells) != ncols) {
    stop("cells have ", ncol(cells), " columns; align has ", ncols)
  }
  rows <- if (nrow(cells) > 0L) {
    paste0(apply(cells, 1, paste, collapse = " & "), " \\\\")
  } else character(0)
  head_block <- c("\\toprule", header, "\\midrule")
  top <- if (env == "longtable") {
    c(if (!is.null(caption)) paste0("\\caption{", caption, "}",
                                    if (!is.null(label)) paste0("\\label{", label, "}"), "\\\\"),
      head_block, "\\endfirsthead", head_block, "\\endhead")
  } else head_block
  writeLines(c(paste0("\\begin{", env, "}{", align, "}"), top, rows,
               "\\bottomrule", paste0("\\end{", env, "}")), path)
}
